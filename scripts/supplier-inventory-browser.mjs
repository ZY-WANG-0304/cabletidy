import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { chromium } from "playwright";
import { createApplication } from "../test/helpers/native-app.mjs";
import { getPaths } from "../test/helpers/native.mjs";
import { catalogFixture } from "../test/helpers/codex-fixture.mjs";

const home = await fs.mkdtemp(path.join(os.tmpdir(), "cabletidy-inventory-browser-"));
const screenshotDir = process.env.CABLETIDY_BROWSER_SCREENSHOTS;
let app, browser;
try {
  app = await createApplication({ paths:getPaths(home), loadCodexCatalog:async () => catalogFixture() });
  let c = (await (await fetch(`${app.url}api/v1/config`)).json()).config;
  const readConfig = async () => (await (await fetch(`${app.url}api/v1/config`)).json()).config;
  const commit = async operation => {
    const response = await fetch(`${app.url}api/v1/config/commit`, {method:"POST",headers:{"content-type":"application/json"},body:JSON.stringify({baseRevision:c.revision,operation})});
    const value = await response.json();
    assert.equal(response.status, 200, JSON.stringify(value));
    c = value.config;
  };
  for (const sid of ["one", "two"]) {
    await commit({type:"supplier.save",supplierId:sid,data:{name:`Supplier ${sid}`,interfaces:{responses:{protocol:"openai.responses",baseUrl:"https://example.invalid/v1",secret:"fixture-token"}}}});
    await commit({type:"supplier.model.save",supplierId:sid,data:{modelId:`wire-${sid}`,model:{identity:"DeepSeek-V4-Pro",interfaces:["responses"],capabilityStates:{tools:"supported",streaming:"supported",reasoning:"supported"},contextWindow:128000,history:"stateless",reasoning:{modes:["effort"],efforts:["high"]}}}});
  }
  browser = await chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1280,height:900}});
  const errors = [];
  page.on("pageerror", error => errors.push(String(error)));
  page.on("dialog", dialog => dialog.accept());
  const screenshot = async name => {
    if (!screenshotDir) return;
    await fs.mkdir(screenshotDir, {recursive:true});
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({path:path.join(screenshotDir, `${name}.png`),fullPage:await page.getByRole("dialog").count() === 0,style:"#toast-region { visibility: hidden; }"});
  };
  const noOverflow = async () => assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  const save = async (form, label) => {
    const response = page.waitForResponse(response => response.url().endsWith("/api/v1/config/commit") && response.request().method() === "POST");
    await form.getByRole("button", {name:label,exact:true}).click();
    const result = await response;
    assert.equal(result.status(), 200, await result.text());
  };

  await page.goto(app.url);
  await page.getByText("服务运行中", {exact:true}).waitFor();
  await page.getByRole("button", {name:"供应商",exact:true}).click();
  assert.equal(await page.getByText("使用情况", {exact:true}).count(), 0);
  assert.equal(await page.locator("#page-content form").count(), 0);
  await screenshot("supplier-list");
  await page.getByRole("button", {name:"新建供应商",exact:true}).click();
  const createForm = page.locator("#supplier-create-form");
  await createForm.waitFor();
  assert.equal(await createForm.locator(":scope > section.panel").count(), 3);
  assert.equal(await createForm.locator('[name="supplierId"], [name="authHeader"], [name="authScheme"]').count(), 0);
  assert.equal(await createForm.getByRole("button", {name:"添加模型",exact:true}).isDisabled(), true);
  await createForm.locator('[name="name"]').fill("Local Service");
  const saveDraft = async (dialog, label) => {
    const response = page.waitForResponse(response => response.url().endsWith("/api/v1/config/validate") && response.request().method() === "POST");
    await dialog.getByRole("button", {name:label,exact:true}).click();
    assert.equal((await response).status(), 200);
    await dialog.waitFor({state:"detached"});
  };
  const beforeDraft = await readConfig();
  await createForm.getByRole("button", {name:"添加接口",exact:true}).click();
  let draftDialog = page.getByRole("dialog");
  assert.equal(await draftDialog.locator('[name="secret"]').getAttribute("required"), "");
  await draftDialog.locator('[name="protocol"]').selectOption("anthropic.messages");
  assert.equal(await draftDialog.locator('[name="authMethod"]').inputValue(), "api-key");
  await draftDialog.locator('[name="protocol"]').selectOption("gemini.generate_content");
  await draftDialog.locator('[name="authMethod"]').selectOption("bearer");
  assert.equal(await draftDialog.locator("[data-supplier-credentials] .field > span").textContent(), "OAuth Access Token");
  await draftDialog.locator('[name="protocol"]').selectOption("openai.responses");
  await draftDialog.locator('[name="authMethod"]').selectOption("none");
  assert.equal(await draftDialog.locator('[name="secret"]').count(), 0);
  await draftDialog.locator('[name="interfaceName"]').fill("Public Responses");
  await draftDialog.locator('[name="baseUrl"]').fill("http://localhost:9999/v1");
  await saveDraft(draftDialog, "保存接口");
  await createForm.getByRole("button", {name:"添加接口",exact:true}).click();
  draftDialog = page.getByRole("dialog");
  await draftDialog.locator('[name="protocol"]').selectOption("anthropic.messages");
  await draftDialog.locator('[name="interfaceName"]').fill("Messages API");
  await draftDialog.locator('[name="baseUrl"]').fill("https://example.invalid/v1");
  await draftDialog.locator('[name="secret"]').fill("fixture-messages-key");
  await saveDraft(draftDialog, "保存接口");
  // Editing a draft preserves its credential and model/interface references.
  await createForm.getByRole("button", {name:"Messages API",exact:true}).click();
  draftDialog = page.getByRole("dialog");
  assert.equal(await draftDialog.locator('[name="secret"]').inputValue(), "fixture-messages-key");
  await saveDraft(draftDialog, "保存接口");
  for (const modelId of ["initial-wire", "second-wire"]) {
    await createForm.getByRole("button", {name:"添加模型",exact:true}).click();
    draftDialog = page.getByRole("dialog");
    await draftDialog.locator('[name="modelId"]').fill(modelId);
    await draftDialog.locator('[name="interfaces"][value="responses"]').check();
    if (modelId === "initial-wire") await draftDialog.locator('[name="interfaces"][value="messages"]').check();
    await saveDraft(draftDialog, "保存模型");
  }
  assert.equal(await createForm.locator(".cable-table").count(), 2);
  assert.equal(await createForm.locator('[name="name"]').inputValue(), "Local Service");
  assert.deepEqual(await readConfig(), beforeDraft);
  await page.getByRole("button", {name:"刷新",exact:true}).click();
  await createForm.getByRole("button", {name:"initial-wire",exact:true}).waitFor();
  assert.equal(await createForm.locator('[name="name"]').inputValue(), "Local Service");
  // A failed model edit remains in its dialog, and cancellation keeps the saved draft.
  await createForm.getByRole("button", {name:"initial-wire",exact:true}).click();
  draftDialog = page.getByRole("dialog");
  await draftDialog.locator('[name="modelId"]').fill("second-wire");
  await draftDialog.getByRole("button", {name:"保存模型",exact:true}).click();
  await draftDialog.locator("[data-form-feedback]").waitFor();
  assert.equal(await draftDialog.locator('[name="modelId"]').inputValue(), "second-wire");
  await page.keyboard.press("Escape");
  await draftDialog.waitFor({state:"detached"});
  assert.equal(await createForm.getByRole("button", {name:"initial-wire",exact:true}).count(), 1);
  await noOverflow();
  await screenshot("supplier-create");
  await page.setViewportSize({width:390,height:844});
  await noOverflow();
  await screenshot("supplier-create-mobile");
  await page.setViewportSize({width:1280,height:900});
  await save(createForm, "创建供应商");
  await page.locator("#supplier-form").waitFor();
  const createdConfig = await readConfig();
  const sid = Object.keys(createdConfig.suppliers).find(id => createdConfig.suppliers[id].name === "Local Service");
  assert.match(sid, /^s-[a-f0-9]{20}$/);
  assert.deepEqual(Object.keys(createdConfig.suppliers[sid].interfaces), ["responses", "messages"]);
  assert.deepEqual(Object.keys(createdConfig.suppliers[sid].models), ["initial-wire", "second-wire"]);
  assert.equal(createdConfig.suppliers[sid].interfaces.messages.secretConfigured, true);
  assert.deepEqual(createdConfig.suppliers[sid].models["initial-wire"].interfaces, ["responses", "messages"]);
  assert.equal(await page.locator("#supplier-create-form").count(), 0);
  assert.equal(await page.locator("#supplier-interface-form, #supplier-model-form").count(), 0);
  assert.equal(await page.locator("#page-content > section.panel").count(), 3);
  assert.equal(await page.locator('#supplier-form .cable-table').count(), 0);
  assert.equal(await page.getByRole("heading", {name:"接口",exact:true}).count(), 1);
  assert.equal(await page.getByRole("heading", {name:"模型",exact:true}).count(), 1);
  assert.equal(await page.locator(".cable-table").count(), 2);

  await page.locator('#supplier-form [name="name"]').fill("Unsaved Name");
  await page.getByRole("button", {name:"添加接口",exact:true}).click();
  let dialog = page.getByRole("dialog");
  await dialog.waitFor();
  assert.equal(await dialog.evaluate(node => node.open), true);
  assert.equal(await dialog.evaluate(node => {const box=node.getBoundingClientRect();return box.top>=0 && box.bottom<=window.innerHeight && box.width<=window.innerWidth;}), true);
  await dialog.locator('[name="interfaceName"]').fill("Authenticated Responses");
  await dialog.locator('[name="baseUrl"]').fill("https://example.invalid/v1");
  await dialog.locator('[name="secret"]').fill("fixture-auth-key");
  await save(dialog, "保存接口");
  await dialog.waitFor({state:"detached"});
  await page.getByRole("button", {name:"Authenticated Responses",exact:true}).click();
  dialog = page.getByRole("dialog");
  assert.equal(await dialog.locator('[name="secret"]').getAttribute("required"), null);
  assert.equal(await dialog.locator('[name="secret"]').getAttribute("placeholder"), "已配置，留空保留现有凭据");
  await dialog.locator('[name="interfaceName"]').fill("Secure Responses");
  await save(dialog, "保存接口");
  await dialog.waitFor({state:"detached"});
  assert.equal((await readConfig()).suppliers[sid].interfaces["responses-2"].secretConfigured, true);
  assert.equal(await page.locator('#supplier-form [name="name"]').inputValue(), "Unsaved Name");
  assert.equal((await readConfig()).suppliers[sid].name, "Local Service");
  await page.locator('#supplier-form [name="name"]').fill("Local Service");

  await page.getByRole("button", {name:"添加模型",exact:true}).click();
  dialog = page.getByRole("dialog");
  await dialog.waitFor();
  assert.equal(await dialog.getByRole("heading", {name:"添加模型",exact:true}).count(), 1);
  assert.equal(await dialog.locator('[name="modelId"]').getAttribute("required"), "");
  await dialog.locator('[name="modelId"]').fill("draft-wire");
  await dialog.locator('[name="interfaces"][value="responses"]').check();
  await dialog.locator('[name="contextWindow"]').fill("-1");
  let response = page.waitForResponse(response => response.url().endsWith("/api/v1/config/commit"));
  await dialog.getByRole("button", {name:"保存模型",exact:true}).click();
  assert.equal((await response).status(), 422);
  await dialog.locator("[data-form-feedback]").waitFor();
  assert.equal(await dialog.locator('[name="modelId"]').inputValue(), "draft-wire");
  assert.equal(await dialog.evaluate(node => node.open), true);
  await dialog.locator('[name="contextWindow"]').fill("128000");
  await screenshot("supplier-model-form");
  await save(dialog, "保存模型");
  await dialog.waitFor({state:"detached"});
  assert.equal(await page.locator(".cable-table").count(), 2);
  await page.getByRole("button", {name:"draft-wire",exact:true}).click();
  dialog = page.getByRole("dialog");
  await dialog.locator('[name="identity"]').fill("Kimi K3");
  await save(dialog, "保存模型");
  await dialog.waitFor({state:"detached"});
  assert.equal((await readConfig()).suppliers[sid].models["draft-wire"].identity, "Kimi K3");
  await page.getByRole("button", {name:"draft-wire",exact:true}).click();
  dialog = page.getByRole("dialog");
  await dialog.locator('[name="identity"]').fill("unsaved");
  await page.keyboard.press("Escape");
  await dialog.waitFor({state:"detached"});
  assert.equal((await readConfig()).suppliers[sid].models["draft-wire"].identity, "Kimi K3");
  await noOverflow();
  await screenshot("supplier-detail");
  await page.setViewportSize({width:390,height:844});
  await noOverflow();
  await screenshot("supplier-detail-mobile");
  await page.getByRole("button", {name:"draft-wire",exact:true}).click();
  await noOverflow();
  assert.equal(await page.getByRole("dialog").evaluate(node => {const box=node.getBoundingClientRect();return box.top>=0 && box.bottom<=window.innerHeight && box.width<=window.innerWidth;}), true);
  await screenshot("supplier-model-form-mobile");
  await page.keyboard.press("Escape");
  await page.setViewportSize({width:1280,height:900});

  await page.getByRole("button", {name:"返回列表",exact:true}).click();
  await page.getByRole("button", {name:"Supplier one",exact:true}).click();
  await page.locator('#supplier-form [name="name"]').fill("Official One");
  await save(page.locator("#supplier-form"), "保存供应商");
  await page.getByRole("button", {name:"线路",exact:true}).click();
  await page.getByRole("button", {name:"新建 Codex 线路",exact:true}).click();
  await page.locator('[name="name"]').fill("Work");
  await page.locator('[name="suppliers"][value="one"]').check();
  await page.locator('[name="suppliers"][value="two"]').check();
  assert.equal(await page.locator('[name="candidate"]:checked').count(), 0);
  await page.getByRole("button", {name:"选择当前筛选结果",exact:true}).click();
  await page.getByRole("button", {name:"将勾选模型加入绑定",exact:true}).click();
  assert.equal(await page.locator('[data-inventory-binding]').count(), 2);
  await page.locator('[name="defaultModel"]').selectOption("wire-one");
  await save(page.locator("#inventory-cable-form"), "保存 Cable");
  await page.getByRole("button", {name:"预览客户端配置",exact:true}).click();
  await page.getByText("Codex local config.toml preview", {exact:true}).waitFor();
  await page.getByRole("button", {name:"应用到 Codex",exact:true}).click();
  await page.getByText("当前激活的 Codex 配置", {exact:true}).waitFor();
  await page.getByRole("button", {name:"撤销接入",exact:true}).click();
  await page.getByText("尚未激活到 Codex 配置", {exact:true}).waitFor();
  await noOverflow();
  await screenshot("cable-detail");
  await page.setViewportSize({width:390,height:844});
  await noOverflow();
  await screenshot("cable-detail-mobile");
  assert.deepEqual(errors, []);
  console.log("Supplier inventory browser checks passed: separate panels, multiple interface/model drafts, atomic creation, generated IDs, authentication, interface/model dialogs, failed-save retention, mobile layout, explicit Cable selection, preview, apply and restore.");
} finally {
  await browser?.close();
  await app?.close();
  await fs.rm(home, {recursive:true,force:true});
}
